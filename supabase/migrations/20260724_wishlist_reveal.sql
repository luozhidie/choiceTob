-- ============================================================
-- 心愿单（需求聚合）价格公开时间字段
-- 用途：心愿单商品先「打码」展示（如 ¥??9），到公开时间后展示真实拿货价。
--       默认规则（前端）：上架时间 created_at + 7 天自动公开。
--       如需「按商品自定义公开时间」，应用本迁移后，在写入/编辑商品时
--       设置 price_reveal_at（ISO 时间）即可覆盖默认 7 天。
-- 说明：不执行本迁移也能正常运行（前端回退到 created_at + 7 天）。
-- ============================================================

ALTER TABLE products
  ADD COLUMN IF NOT EXISTS price_reveal_at timestamptz;

COMMENT ON COLUMN products.price_reveal_at IS
  '心愿单商品的价格公开时间；为空时前端按 上架时间+7天 自动公开';
